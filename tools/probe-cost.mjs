import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
await page.goto('http://127.0.0.1:5273/', { waitUntil: 'load', timeout: 60000 });
await page.waitForFunction('window.__READY__ === true', { timeout: 40000 });
await page.waitForTimeout(1500);
const measure = () => page.evaluate(() => new Promise((resolve) => {
  const times = []; let last = performance.now(); let n = 0;
  const tick = () => { const now = performance.now(); times.push(now - last); last = now; if (++n < 100) requestAnimationFrame(tick); else { const s = times.reduce((a,b)=>a+b,0); resolve(+(1000/(s/times.length)).toFixed(1)); } };
  requestAnimationFrame(tick);
}));
const out = {};
out.baseline = await measure();
await page.evaluate(() => { const S = window.__SCENE__; S.renderer.shadowMap.enabled = false; });
out.noShadow = await measure();
await page.evaluate(() => { const S = window.__SCENE__; S.renderer.shadowMap.enabled = true; S.dof.enabled = false; });
out.noDof = await measure();
await page.evaluate(() => { const S = window.__SCENE__; S.dof.enabled = true; S.composer.passes.forEach(p => { if (p.effects) p.effects.forEach(e => { if (e.constructor.name === 'ChromaticAberrationEffect') e.enabled = false; }); }); });
out.noCA = await measure();
await page.evaluate(() => { const S = window.__SCENE__; S.dof.enabled = true; S.renderer.setPixelRatio(0.7); });
out.pr07 = await measure();
console.log(JSON.stringify(out));
await browser.close();
